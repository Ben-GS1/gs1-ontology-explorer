#!/usr/bin/env node
// Turns the already-built dist/index.html into api/src/app-shell.js — a
// plain CommonJS module exporting the HTML as a string — for
// api/src/lib/shell.js to require() at runtime.
//
// Run this after `npm run build`, before deploying (or locally running)
// the API. See:
//   - the "Copy SPA shell into API" step in
//     .github/workflows/azure-static-web-apps.yml
//   - the "Local development" section of README.md
//
// Deliberately generated as a .js module rather than left as a loose
// .html file: it's require()'d by shell.js exactly like any other source
// file, so it's guaranteed to be included in the API's deployment package
// the same way resolve.js and shell.js themselves reliably are — with no
// dependence on whatever asset-packaging conventions Azure's Oryx build
// may or may not apply to non-code static files.
import { readFileSync, writeFileSync } from "node:fs";

const html = readFileSync("dist/index.html", "utf-8");
const body = `// Generated by scripts/generate-app-shell.mjs from dist/index.html.
// Do not edit directly — this file is regenerated on every build/deploy.
module.exports = ${JSON.stringify(html)};
`;

writeFileSync("api/src/app-shell.js", body);
console.log(`Wrote api/src/app-shell.js (${body.length} bytes)`);
